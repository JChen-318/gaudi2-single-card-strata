// The device kernel takes the codebook as its fourth input; tests keep calling the old signature
// and get the same generated bytes here, so a layout drift is caught by the blob's own test rather
// than silently reading past the tensor.
inline void packed_kernel(tensor w,tensor a,tensor m,tensor o,int columns,int rows,int batch,int type,int mode) {
    static_assert(sizeof(::strata::hpu::detail::packed_codebook_blob_data.bytes)==STRATA_PACKED_CODEBOOK_BYTES,"emulator codebook size drifted");
    tensor c{const_cast<uint8_t*>(::strata::hpu::packed_codebook_blob()),{STRATA_PACKED_CODEBOOK_BYTES,1},1};
    packed_kernel_main(w,a,m,c,o,columns,rows,batch,type,mode);
}
